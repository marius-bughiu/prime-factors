"""Find integer points on a conic by constructing one auxiliary equation per residue class."""
import argparse
from functools import partial
import json
from math import comb, gcd, isqrt, prod

from .norm_auxiliary import integer_roots, short_vector
from .norm_directions import search as norm_search


COUNTERS = ('auxiliary_equations', 'empty_classes', 'lll_calls', 'lll_swaps',
            'lll_reductions', 'integer_root_nodes', 'hensel_steps', 'kernel_constraints')


def chart_prime(total, d):
    """A prime away from 2*d*total makes every solution a smooth point."""
    prime = 3
    while total % prime == 0 or d % prime == 0 or any(prime % k == 0 for k in range(3, isqrt(prime)+1, 2)):
        prime += 2
    return prime


def weights_and_modulus(xmax, ymax, degree, prime):
    # Basis 1,x,...,x^D,y,xy,...,x^(D-1)y.
    weights = [xmax**i for i in range(degree+1)] + [ymax*xmax**i for i in range(degree)]
    size = len(weights)
    limit = size**(2*size) * 2**(size*(size-1)) * prod(weights)**4
    exponent = 2*size*(size-1)
    modulus = prime
    while modulus**exponent <= limit:
        modulus *= prime
    return weights, modulus


def taylor_rows(total, a, b, u, v, prime, modulus, degree, work):
    """Images of basis monomials under x=u+H, y=Y(H) modulo Q^(2D), H^(2D)."""
    order = 2*degree
    precision = modulus**order
    known = prime
    while known < precision:
        known = min(known*known, precision)
        error = a*u*u + b*v*v - total
        v = (v - error*pow(2*b*v, -1, known)) % known
        work['hensel_steps'] += 1
    inverse = pow(2*b*v, -1, precision)
    y = [v]
    for j in range(1, order):
        contribution = 2*a*u if j == 1 else (a if j == 2 else 0)
        contribution += b*sum(y[i]*y[j-i] for i in range(1, j))
        y.append(-contribution*inverse % precision)
    powers = [[comb(i,j)*u**(i-j) % precision if j <= i else 0
               for j in range(order)] for i in range(degree+1)]
    mixed = [[sum(x[i]*y[j-i] for i in range(j+1)) % precision for j in range(order)]
             for x in powers[:-1]]
    return powers + mixed


def coefficient_lattice(images, modulus, work):
    """Intersect the integer row lattice with each Taylor-coefficient congruence."""
    size = len(images)
    rows = [[int(i == j) for j in range(size)] for i in range(size)]
    for j in range(size-1):
        precision = modulus**(size-1-j)
        column = [image[j] for image in images]
        residues = [sum(x*y for x,y in zip(row, column)) % precision for row in rows]
        pivot = min(range(size), key=lambda i: gcd(residues[i], precision))
        divisor = gcd(residues[pivot], precision)
        if divisor == precision:
            continue
        # All gcds are powers of one prime. The image is generated by this pivot.
        work['kernel_constraints'] += 1
        step = precision//divisor
        inverse = pow(residues[pivot]//divisor, -1, step)
        base = rows[pivot]
        for i, residue in enumerate(residues):
            if i != pivot and residue:
                multiple = residue//divisor*inverse % step
                if 2*multiple > step:
                    multiple -= step
                rows[i] = [x-multiple*y for x,y in zip(rows[i], base)]
        rows[pivot] = [step*x for x in base]
    return rows


def square_coefficients(coefficients):
    square = [0]*(2*len(coefficients)-1)
    for i, x in enumerate(coefficients):
        for j, y in enumerate(coefficients):
            square[i+j] += x*y
    return square


def intersections(total, a, b, u, modulus, xmax, coeffs, work):
    """Eliminate y, then isolate roots only on the requested x progression."""
    degree = len(coeffs)//2
    p, h = coeffs[:degree+1], coeffs[degree+1:]
    eliminant = [b*c for c in square_coefficients(p)]
    for i, c in enumerate(square_coefficients(h)):
        eliminant[i] -= total*c
        eliminant[i+2] += a*c
    if not any(eliminant):
        raise ArithmeticError('auxiliary equation vanished identically on a nonsingular conic')
    # Substitute x = u + Q*j and remove the integer content before isolating roots.
    poly = [modulus**j * sum(comb(i,j)*c*u**(i-j) for i,c in enumerate(eliminant) if i >= j)
            for j in range(len(eliminant))]
    content = gcd(*poly)
    # The same eliminant includes the opposite y branch. Signed x includes the
    # opposite residue class as well. For u=0 both abscissa signs coincide as classes.
    lower = 1 if u == 0 else -((xmax+u)//modulus)
    for j in integer_roots([c//content for c in poly], lower, (xmax-u)//modulus, work):
        x = abs(u+modulus*j)
        ysquared, rem = divmod(total-a*x*x, b)
        if not rem and ysquared > 0:
            work['discriminant_roots'] += 1
            y = isqrt(ysquared)
            if y*y == ysquared:
                yield x, y


def residue_points(total, d, prime):
    """Partition the solutions mod prime into disjoint charts with unit y derivative."""
    roots = {}
    for y in range(prime):
        roots.setdefault(d*y*y % prime, []).append(y)
    for x in range(prime):
        for y in roots.get((total-x*x) % prime, []):
            if 0 < y <= prime//2:
                yield 1, d, x, y, False
            elif y == 0 and 0 < x <= prime//2:
                yield d, 1, y, x, True


def scan(n, d, k, work, max_blocks, *, degree=2):
    total = n*k
    if total < 1+d:
        return
    prime = chart_prime(total, d)
    for a,b,x0,y0,swapped in residue_points(total, d, prime):
        xmax, ymax = isqrt((total-b)//a), isqrt((total-a)//b)
        weights, modulus = weights_and_modulus(xmax, ymax, degree, prime)
        for u in range(x0, min(modulus//2, xmax)+1, prime):
            if work['blocks'] >= max_blocks:
                work['outcome'] = 'block_limit'
                return
            work['blocks'] += 1
            positions = (xmax-u)//modulus + ((xmax+u)//modulus+1 if u else 0)
            work['coordinate_positions'] += positions
            if not positions:
                work['empty_classes'] += 1
                continue
            images = taylor_rows(total, a, b, u, y0, prime, modulus, degree, work)
            lattice = coefficient_lattice(images, modulus, work)
            weighted = [[c*w for c,w in zip(row, weights)] for row in lattice]
            precision = modulus**(2*degree)
            # A sufficiently short basis row is already a certificate.
            vec = min(weighted, key=lambda row: sum(map(abs, row)))
            if sum(map(abs, vec)) >= precision:
                vec = short_vector(weighted, work)
            if not any(vec) or sum(map(abs,vec)) >= precision:
                raise ArithmeticError('LLL length did not certify a vanishing equation')
            coeffs = [v//w for v,w in zip(vec, weights)]
            work['auxiliary_equations'] += 1
            for x,y in intersections(total, a, b, u, modulus, xmax, coeffs, work):
                yield (y,x) if swapped else (x,y)


def search(n, last_prime, max_blocks, degree=2):
    if degree < 1:
        raise ValueError('expected positive degree')
    return norm_search(n, last_prime, max_blocks, scanner=partial(scan, degree=degree),
                       work_counts=COUNTERS)


