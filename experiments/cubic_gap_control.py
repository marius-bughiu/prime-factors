"""Construct an off-diagonal full-size control within the cube-root gap window."""

import argparse
from collections import Counter
import json
from math import gcd, isqrt
from pathlib import Path

from .certified_control import lean_source, prime_chain
from .cubic_forced_units import diagonal
from .cubic_gap_window import search
from .offset_tangent_cover import cube_root
from scripts.factor import primes_through, verify_file

ROOT = Path(__file__).resolve().parents[1]
RECORD = ROOT/'research/cubic-gap-control.json'
PROOF = ROOT/'benchmarks/controls/CubicGapControl.lean'
DOMAIN = 'cubic-gap-window-off-diagonal-v1'


def generate():
    chain = prime_chain(DOMAIN, 513)
    r = int(chain[-1]['prime'])
    # Choose two primes 1 modulo r, with their half-gap close to the public
    # cube-root prediction but displaced by about 2^338. The scan sees only N.
    target_prime = 13 << 1020
    d = r*(cube_root(4*target_prime**2)//r)
    target_estimate = d-(1 << 338)
    start = (isqrt(target_estimate**3//4+d*d)-d-1)//(2*r)
    primes = primes_through(8191)
    work = Counter()
    length = 100000
    for block in range(1024):
        first = start+block*length
        live = bytearray([1])*length
        for prime in primes:
            if (2*r) % prime == 0:
                continue
            inverse = pow(2*r, -1, prime)
            for add in (1, 1+2*d):
                offset = (-add*inverse-first) % prime
                live[offset::prime] = bytes((length-offset+prime-1)//prime)
        pos = live.find(1)
        while pos >= 0:
            k = first+pos
            p = 2*r*k+1
            q = p+2*d
            nodes = []
            for side, value in (('left', p), ('right', q)):
                work[side+'_tested'] += 1
                mul = (value-1)//r
                z = pow(2, mul, value)
                if gcd(z-1,value) != 1 or pow(z,r,value) != 1 or value > r*r:
                    break
                nodes.append(dict(bits=1024, prime=str(value), multiplier=str(mul//2),
                                  order_witness=str(z)))
            if len(nodes)==2:
                n = p*q
                measured = search(n)
                if n.bit_length()!=2048 or min(p,q).bit_length()!=1024 or max(p,q).bit_length()!=1024:
                    raise ArithmeticError('constructed primes exceeded their bit interval')
                if measured['factors']!=[str(p),str(q)] or diagonal(n)['factors']:
                    raise ArithmeticError('new control did not separate the two searches')
                error = d-int(measured['half_gap_estimate'])
                if not 2**337 <= abs(error) <= 2**339:
                    raise ArithmeticError('constructed half-gap missed its claimed error band')
                record = {'domain': DOMAIN, 'offset_index': k-start, 'shared_prime_order': str(r),
                          'product': str(n), 'factors': [str(p),str(q)], 'actual_half_gap': str(d),
                          'half_gap_error': str(error), 'error_bits': abs(error).bit_length(),
                          'fermat_tests_to_midpoint': str((p+q)//2-isqrt(n-1)),
                          'construction_work': dict(work), 'search': measured}
                proof_data = dict(product=str(n), chains={key: chain+[node] for key,node in zip(('left','right'),nodes)})
                source = lean_source(proof_data, include_signature=False,
                                     generator_comment='Generated by experiments/cubic_gap_control.py using a shared certified prime order.')
                cube = int(measured['half_gap_estimate'])-1
                source = 'import PrimeFactors.CubicGapWindow\n'+source+f'''
namespace PrimeFactors.Generated
private abbrev actualGap : ℕ := {d}

theorem gap_recovered : CubicGapWindow.readout controlProduct=(left1024,right1024) := by
  apply CubicGapWindow.recover_certificate (d:=actualGap) (c:={cube}) <;> decide +kernel

theorem gap_control_checks : CubicGapWindow.readout controlProduct=(left1024,right1024) ∧
    ExactFactorization controlProduct [left1024,right1024] := ⟨gap_recovered,factorization⟩

#print axioms gap_recovered
#print axioms gap_control_checks
end PrimeFactors.Generated
'''
                return record,source
            pos = live.find(1,pos+1)
    raise ArithmeticError('bounded prime construction exhausted')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--write', action='store_true')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args()
    record,source = generate()
    body = json.dumps(record, indent=2)+'\n'
    if args.write:
        RECORD.write_text(body)
        PROOF.write_text(source)
    elif RECORD.read_text()!=body or PROOF.read_text()!=source:
        raise SystemExit('off-diagonal control did not reproduce')
    verify_file(PROOF, 'PrimeFactors.Generated.gap_control_checks')
    print(f"Verified the 2,048-bit off-diagonal factorization, with a {record['error_bits']}-bit half-gap error.")
