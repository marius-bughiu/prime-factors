"""Generate kernel receipts for the two published products using no factor data."""

import argparse
import json
from math import isqrt
from pathlib import Path
from time import perf_counter

from experiments.intermediate_totient_rows import product_band
from scripts.factor import verify_file


ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "benchmarks" / "intermediate-totient-rows.json"
CONTROLS = {
    "fresh": "intermediate-totient-fresh-2048",
    "crossed": "intermediate-totient-crossed-2048",
}


def source(n: int, bits: int, reported_rows: int) -> str:
    if n.bit_length() != 2048 or bits != 1024:
        raise ValueError("the theorem requires a 2048-bit product and 1024-bit factor width")
    low, high = product_band(n, bits)
    return f"""import PrimeFactors.IntermediateMenuCertificate

/- Generated by experiments/intermediate_menu_receipt.py from the public product and width.
The kernel computes the LCMs, checks their size gate, locates each window, and inspects
the native rows. No factor or totient is supplied to the computation. -/
namespace PrimeFactors.GeneratedIntermediateMenu

open IntermediateMenuCertificate IntermediateTotientObstruction LcmConvergentObstruction
set_option maxRecDepth 8192
set_option maxHeartbeats 10000000
set_option exponentiation.threshold 4096

def n : ℕ := {n}
def widthFloor : ℕ := 2^{bits - 1}
def low : ℕ := {low}
def high : ℕ := {high}

private theorem window_check : ProductDeficitBand.lower n widthFloor=low ∧
    ProductDeficitBand.upper n widthFloor=high := by
  let s : ℕ := {isqrt(n - 1) + 1}
  have above : ceilSqrt n≤s := ceilSqrt_le_iff.mpr (by decide +kernel)
  have below : s≤ceilSqrt n := by
    by_contra! h
    have cap := ceilSqrt_le_iff.mp (show ceilSqrt n≤s-1 by omega)
    exact (not_le_of_gt (by decide +kernel : (s-1)^2<n)) cap
  rw [ProductDeficitBand.lower,le_antisymm above below]
  decide +kernel

private theorem menu_check : (profile n 1432).2.length=106 ∧
    (profile n 1432).2.Nodup ∧
    ((profile n 1432).2.map (fun E => windowWidth n E low high)).sum={reported_rows} ∧
    (profile n 1432).2.all (fun E => goodWindow n E low high)=true := by decide +kernel

/-- Among the 106 distinct gated exponents, none has an integer intermediate candidate
in the verified public interval. This rules out every eligible prefix index for any
same-width odd factorization, including all indices producing duplicate exponents. -/
theorem checked : (profile n 1432).2.length=106 ∧ (profile n 1432).2.Nodup ∧
    ((profile n 1432).2.map (fun E => windowWidth n E low high)).sum={reported_rows} ∧
    (profile n 1432).2.all (fun E => goodWindow n E low high)=true ∧
    ∀ p q j : ℕ, p*q=n → Odd p → Odd q → widthFloor≤p → widthFloor≤q →
      p<2*widthFloor → q<2*widthFloor → prefixLCM j≤n → 4*n≤(prefixLCM j+1)^2 →
      ¬Hit n (prefixLCM j) ((p-1)*(q-1)) := by
  refine ⟨menu_check.1,menu_check.2.1,menu_check.2.2.1,menu_check.2.2.2,?_⟩
  intro p q j product po qo pl ql pu qu fits gate
  exact control (by decide +kernel) (by decide +kernel) (by decide +kernel)
    (show Even widthFloor from ⟨2^{bits - 2},by decide +kernel⟩)
    window_check.1 window_check.2 menu_check.2.2.2 product po qo pl ql pu qu fits gate

#print axioms checked
end PrimeFactors.GeneratedIntermediateMenu
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check both generated receipts with Lean")
    parser.add_argument("--control", choices=CONTROLS, help="generate just one of the two receipts")
    args = parser.parse_args()
    cases = {case["id"]: case for case in json.loads(FIXTURE.read_text())}
    destination = ROOT / "build" / "site" / "proofs"
    destination.mkdir(parents=True, exist_ok=True)
    for name, case_id in CONTROLS.items():
        if args.control and name != args.control:
            continue
        case = cases[case_id]
        path = destination / f"intermediate-menu-exclusion-{name}-2048.lean"
        reported_rows = case["checks"]["counts"]["width_indices"]
        path.write_text(source(int(case["n"]), case["factor_bits"], reported_rows))
        if args.check:
            started = perf_counter()
            verify_file(path, "PrimeFactors.GeneratedIntermediateMenu.checked")
            print(f"{name}: verified 106 distinct eligible prefix powers and {reported_rows} coefficients in {perf_counter()-started:.2f}s", flush=True)
        else:
            print(path)


if __name__ == "__main__":
    main()
