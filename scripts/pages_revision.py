"""Choose a verified main artifact while holding the GitHub Pages deployment lock."""

import json
import os
from pathlib import Path
import subprocess


WORKFLOW = 'actions/workflows/verify.yml/runs'


def api_pages(endpoint):
    response = subprocess.check_output(['gh', 'api', '--paginate', '--slurp', endpoint], text=True)
    return json.loads(response)


def records(pages, field, *, filtered=False):
    """Check pagination before using the absence of a passing run to authorize deployment."""
    if not pages:
        raise ValueError('GitHub returned no response pages')
    counts = {page['total_count'] for page in pages}
    rows = [row for page in pages for row in page[field]]
    # GitHub caps searches using head_sha (among other filters) at 1,000 results.
    if filtered and max(max(counts), len(rows)) >= 1000:
        return None
    if counts != {len(rows)} or len({row['id'] for row in rows}) != len(rows):
        raise ValueError(f'incomplete or inconsistent GitHub pagination for {field}')
    return rows


def passing_run(repo, sha, fetch=api_pages):
    endpoint = f'repos/{repo}/{WORKFLOW}'
    runs = records(fetch(f'{endpoint}?head_sha={sha}&per_page=100'), 'workflow_runs', filtered=True)
    if runs is None:
        # Without search filters this endpoint can paginate past the search ceiling.
        runs = records(fetch(f'{endpoint}?per_page=100'), 'workflow_runs')
    for run in runs:
        if run['head_sha'] != sha or run['head_branch'] != 'main' or run['event'] not in ('push', 'workflow_dispatch'):
            continue
        run_id = run['id']
        jobs = records(fetch(f'repos/{repo}/actions/runs/{run_id}/jobs?filter=all&per_page=100'), 'jobs')
        for job in jobs:
            if (job['head_sha'] != sha or job['run_id'] != run_id or job['name'] != 'verify'
                    or job['status'] != 'completed' or job['conclusion'] != 'success'):
                continue
            # A dispatch may name a tag instead of the branch. Only the real main ref
            # runs the artifact upload. Recognize its old autogenerated step name too.
            if run['event'] == 'workflow_dispatch' and not any(
                    step['conclusion'] == 'success' and (step['name'] == 'Upload verified main artifact'
                    or step['name'].startswith('Run actions/upload-pages-artifact@')) for step in job['steps']):
                continue
            return run_id
    return None


def skip_reason(candidate, main, verified, cwd=None):
    ancestor = subprocess.run(['git', 'merge-base', '--is-ancestor', candidate, main], cwd=cwd)
    if ancestor.returncode == 1:
        return f'{candidate} is no longer on main ({main})'
    ancestor.check_returncode()
    # Include incomparable former main tips when a merge reconnects rewritten history.
    # Publishing either sibling over the other would discard already verified changes.
    newer = subprocess.check_output(['git', 'rev-list', f'{candidate}..{main}'], cwd=cwd, text=True)
    for sha in newer.splitlines():
        run = verified(sha)
        if run is not None:
            return f'main revision {sha} outside this artifact already passed verification in run {run}'
    return None


def main():
    candidate = os.environ['GITHUB_SHA']
    tip = subprocess.check_output(['git', 'rev-parse', '--verify', 'refs/remotes/origin/main'], text=True).strip()
    reason = skip_reason(candidate, tip, lambda sha: passing_run(os.environ['GITHUB_REPOSITORY'], sha))
    print(f'Skipping publication: {reason}' if reason else f'Publishing verified revision {candidate} (main at {tip}).')
    with Path(os.environ['GITHUB_OUTPUT']).open('a') as output:
        print(f'eligible={str(reason is None).lower()}', file=output)


if __name__ == '__main__':
    main()
